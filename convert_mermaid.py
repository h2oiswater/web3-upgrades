import re

def replace_block(content, old_text, mermaid_text):
    """Replace a code-block with mermaid, ensuring exact match."""
    old_wrapped = f'<pre class="code-block"><code>{old_text}</code></pre>'
    new_wrapped = f'<pre class="mermaid">\n{mermaid_text}\n</pre>'
    if old_wrapped not in content:
        print(f"WARNING: Could not find exact match for block!")
        print(f"Looking for: {old_wrapped[:100]}...")
        return None
    return content.replace(old_wrapped, new_wrapped, 1)

